function stop(placeKey: string, stay: number, extra: Partial<Stop> = {}): Stop {
  return { id: uid(), placeId: `p-${placeKey}`, stay, ...extra }
}

function day(title: string, startTime: string, stops: Stop[], lodging?: string, extra: Partial<Day> = {}): Day {
  return { id: uid(), title, startTime, stops, lodgingPlaceId: lodging ? `p-${lodging}` : undefined, ...extra }
}

